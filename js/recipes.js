let savedRecipes = [];

try {
    savedRecipes = JSON.parse(localStorage.getItem('userRecipes')) || [];
} catch (error) {
    savedRecipes = [];
}


let changed = false;

savedRecipes.forEach(function(item){
    if(!item.id) {
        item.id = 'u' + Date.now() + Math.floor(Math.random() * 1000);
        changed = true;
    }
    if (!item.ingredients) {
        item.ingredients = [];
        changed = true;
    }
    if (!item.steps) {
        item.steps = [];
        changed = true;
    }

});

if (changed) {
    localStorage.setItem('userRecipes', JSON.stringify(savedRecipes));
}

recipes.unshift(...savedRecipes);

function escapeHtml(text) {
    const div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML;
}

function getFavorites() {
    try {
        return JSON.parse(localStorage.getItem('favorites')) || [];
    } catch (error) {
        return [];
    }
}

function isFavorite(id) {
    return getFavorites().includes(id);
}

function toggleFavorite(id) {
    let favorites = getFavorites();

    if (favorites.includes(id)) {
        favorites = favorites.filter(function (item) {
            return item !== id;
        });
    } else {
        favorites.push(id);
    }

    localStorage.setItem('favorites', JSON.stringify(favorites));
}










    